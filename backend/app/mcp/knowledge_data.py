def get_documents_by_category(category: str) -> list[dict[str, Any]]:
    """Get documents filtered by category."""
    return [doc for doc in MOCK_KNOWLEDGE_DOCUMENTS if doc["category"] == category]


def get_document_by_id(doc_id: str) -> dict[str, Any] | None:
    """Get a single document by ID."""
    for doc in MOCK_KNOWLEDGE_DOCUMENTS:
        if doc["id"] == doc_id:
            return doc
    return None
